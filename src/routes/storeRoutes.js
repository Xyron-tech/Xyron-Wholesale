import {Router} from "express";
import {rateLimit} from "express-rate-limit";
import multer from "multer";
import {createProduct,createSliderSlide,deleteProduct,deleteSliderSlide,getPublicProducts,getPublicStore,getStorefrontSettings,listOwnerProducts,setProductFeatured,updatePaymentSettings,updateProduct,updateShippingSettings,updateSliderSlide,updateStoreProfile,updateStoreSections} from "../controllers/storeController.js";
import {createCustomerRecoveryRequest,deleteCustomerProfile,getCustomerSession,loginCustomer,logoutCustomer,registerCustomer,updateCustomerProfile} from "../controllers/customerAuthController.js";
import {asyncHandler} from "../middleware/asyncHandler.js";
import {optionalCustomerAuth,requireActiveBusiness,requireAuth,requireCustomerAuth} from "../middleware/auth.js";
import {archiveBusinessOrder,archiveCustomerOrder,createCustomerOrder,getBusinessOrder,getBusinessOrderAnalytics,getCustomerOrder,listBusinessOrders,listCustomerOrders,customerOrderAccess,markCustomerOrderNotificationsRead,sendBusinessOrderBill,updateBusinessOrderStatus} from "../controllers/orderController.js";
import {getBusinessInboxCounts,getCustomerInboxCounts,listBusinessNotifications,markBusinessNotificationRead} from "../controllers/supportController.js";
import {getPincodeDetails,getPincodeRegions} from "../controllers/shippingController.js";
import {createBusinessPlanUpgradeRequest} from "../controllers/planUpgradeController.js";

const imageUpload=multer({storage:multer.memoryStorage(),limits:{fileSize:5*1024*1024,files:1}});
const publicOrderWriteLimit=rateLimit({windowMs:15*60*1000,limit:30,standardHeaders:"draft-7",legacyHeaders:false});
const customerAuthLimit=rateLimit({windowMs:15*60*1000,limit:10,standardHeaders:"draft-7",legacyHeaders:false});
const customerRecoveryLimit=rateLimit({windowMs:60*60*1000,limit:5,standardHeaders:"draft-7",legacyHeaders:false});
const pincodeLookupLimit=rateLimit({windowMs:15*60*1000,limit:120,standardHeaders:"draft-7",legacyHeaders:false});
const router=Router();

router.get("/stores/:slug",asyncHandler(getPublicStore));
router.get("/stores/:slug/products",asyncHandler(getPublicProducts));
router.get("/pincodes/regions",pincodeLookupLimit,asyncHandler(getPincodeRegions));
router.get("/pincodes/:pincode",pincodeLookupLimit,asyncHandler(getPincodeDetails));
router.post("/stores/:slug/customer/register",customerAuthLimit,asyncHandler(registerCustomer));
router.post("/stores/:slug/customer/login",customerAuthLimit,asyncHandler(loginCustomer));
router.get("/stores/:slug/customer/me",optionalCustomerAuth,asyncHandler(getCustomerSession));
router.get("/stores/:slug/customer/inbox-counts",requireCustomerAuth,asyncHandler(getCustomerInboxCounts));
router.post("/stores/:slug/customer/logout",asyncHandler(logoutCustomer));
router.patch("/stores/:slug/customer/profile",requireCustomerAuth,asyncHandler(updateCustomerProfile));
router.delete("/stores/:slug/customer/profile",requireCustomerAuth,asyncHandler(deleteCustomerProfile));
router.get("/stores/:slug/customer/orders",requireCustomerAuth,asyncHandler(listCustomerOrders));
router.delete("/stores/:slug/customer/orders/:orderNumber",requireCustomerAuth,asyncHandler(archiveCustomerOrder));
router.post("/stores/:slug/customer/recovery-requests",customerRecoveryLimit,asyncHandler(createCustomerRecoveryRequest));
router.post("/stores/:slug/orders",publicOrderWriteLimit,requireCustomerAuth,asyncHandler(createCustomerOrder));
router.get("/stores/:slug/orders/:orderNumber",optionalCustomerAuth,customerOrderAccess,asyncHandler(getCustomerOrder));
router.post("/stores/:slug/orders/:orderNumber/notifications/read",optionalCustomerAuth,customerOrderAccess,asyncHandler(markCustomerOrderNotificationsRead));
router.get("/orders/:orderNumber",customerOrderAccess,asyncHandler(getCustomerOrder));

router.use("/business",requireAuth,requireActiveBusiness);
router.get("/business/storefront",asyncHandler(getStorefrontSettings));
router.post("/business/plan-upgrade-requests",asyncHandler(createBusinessPlanUpgradeRequest));
router.get("/business/inbox-counts",asyncHandler(getBusinessInboxCounts));
router.get("/business/notifications",asyncHandler(listBusinessNotifications));
router.post("/business/notifications/:id/read",asyncHandler(markBusinessNotificationRead));
router.patch("/business/profile",imageUpload.single("image"),asyncHandler(updateStoreProfile));
router.patch("/business/payment-settings",imageUpload.single("image"),asyncHandler(updatePaymentSettings));
router.patch("/business/shipping-settings",asyncHandler(updateShippingSettings));
router.patch("/business/store-sections",asyncHandler(updateStoreSections));
router.get("/business/products",asyncHandler(listOwnerProducts));
router.post("/business/products",imageUpload.single("image"),asyncHandler(createProduct));
router.patch("/business/products/:id",imageUpload.single("image"),asyncHandler(updateProduct));
router.patch("/business/products/:id/featured",asyncHandler(setProductFeatured));
router.delete("/business/products/:id",asyncHandler(deleteProduct));
router.get("/business/orders",asyncHandler(listBusinessOrders));
router.get("/business/orders/:id",asyncHandler(getBusinessOrder));
router.patch("/business/orders/:id/archive",asyncHandler(archiveBusinessOrder));
router.get("/business/analytics",asyncHandler(getBusinessOrderAnalytics));
router.patch("/business/orders/:id/status",asyncHandler(updateBusinessOrderStatus));
router.post("/business/orders/:id/bill",asyncHandler(sendBusinessOrderBill));
router.post("/business/slides",imageUpload.single("image"),asyncHandler(createSliderSlide));
router.patch("/business/slides/:id",imageUpload.single("image"),asyncHandler(updateSliderSlide));
router.delete("/business/slides/:id",asyncHandler(deleteSliderSlide));

export default router;
